// Fetches the site price list from the CRM and writes src/auto/services.mjs.
// Run as `npm run fetch-services`; `CRM_URL` (env or .env) points it at a
// local CRM, e.g. CRM_URL=http://localhost:3000. Any failure exits with 1, so
// the build never ships an empty or broken price list.
import fs from "fs/promises";
import path from "path";
import { fileURLToPath } from "url";

export const DEFAULT_CRM_URL = "https://admin.svadlenka-praha.cz";
export const PRICE_LIST_PATH = "/api/public/price-list";
const OUT_FILE = "./src/auto/services.mjs";

const isNonEmptyString = (value) =>
  typeof value === "string" && value.trim() !== "";

// Validates the CRM feed `{categories:[{title, rows:[{name, price, …}]}]}` and
// maps it to the getServices() shape `[{title, options:[[name, price]]}]`.
// The raw price fields are ignored: the rendered `price` is translated per msgid.
export function toServices(json) {
  if (!json || !Array.isArray(json.categories)) {
    throw new Error("price list: `categories` is not an array");
  }
  if (json.categories.length === 0) {
    throw new Error("price list: no categories");
  }
  const services = json.categories.map((category, i) => {
    if (!isNonEmptyString(category?.title)) {
      throw new Error(`price list: category ${i} has no title`);
    }
    if (!Array.isArray(category.rows)) {
      throw new Error(`price list: "${category.title}" rows is not an array`);
    }
    return {
      title: category.title,
      options: category.rows.map((row, j) => {
        if (!isNonEmptyString(row?.name) || !isNonEmptyString(row?.price)) {
          throw new Error(
            `price list: "${category.title}" row ${j} needs a name and a price`,
          );
        }
        return [row.name, row.price];
      }),
    };
  });
  if (services.every((service) => service.options.length === 0)) {
    throw new Error("price list: no rows");
  }
  return services;
}

// Escapes a string for the body of a template literal.
const escapeTemplate = (value) =>
  value.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");

const tag = (value) => `t\`${escapeTemplate(value)}\``;

export function toModule(services, { source, generatedAt }) {
  const categories = services
    .map(
      (service) => `  {
    title: ${tag(service.title)},
    options: [
${service.options.map(([name, price]) => `      [${tag(name)}, ${tag(price)}],`).join("\n")}
    ],
  },`,
    )
    .join("\n");
  return `// generated by npm run fetch-services from ${source} at ${generatedAt}
import { t } from "ttag";

export const getServices = () => [
${categories}
];
`;
}

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

// GETs the price list, retrying because the CRM may be mid-restart.
export async function fetchPriceList(
  url,
  { attempts = 3, delayMs = 3_000, timeoutMs = 15_000 } = {},
) {
  let lastError;
  for (let attempt = 1; attempt <= attempts; attempt++) {
    try {
      const response = await fetch(url, {
        signal: AbortSignal.timeout(timeoutMs),
      });
      if (!response.ok) {
        throw new Error(`GET ${url} responded ${response.status}`);
      }
      return await response.json();
    } catch (error) {
      lastError = error;
      console.warn(
        `price list: attempt ${attempt}/${attempts} failed: ${error.message}`,
      );
      if (attempt < attempts) await sleep(delayMs);
    }
  }
  throw lastError;
}

export async function fetchServices({
  crmUrl = process.env.CRM_URL || DEFAULT_CRM_URL,
  outFile = OUT_FILE,
  ...fetchOptions
} = {}) {
  const url = `${crmUrl.replace(/\/+$/, "")}${PRICE_LIST_PATH}`;
  const services = toServices(await fetchPriceList(url, fetchOptions));
  const source = toModule(services, {
    source: url,
    generatedAt: new Date().toISOString(),
  });
  await fs.mkdir(path.dirname(outFile), { recursive: true });
  await fs.writeFile(outFile, source, "utf8");
  const rows = services.reduce((n, service) => n + service.options.length, 0);
  console.log(
    `price list: ${services.length} categories, ${rows} rows from ${url} → ${outFile}`,
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    await fetchServices();
  } catch (error) {
    console.error(`fetch-services failed: ${error.message}`);
    process.exit(1);
  }
}
