// Fetches the published opening hours from the CRM and writes
// src/auto/openingHours.mjs. Run as `npm run fetch-opening-hours`; `CRM_URL`
// (env or .env) points it at a local CRM. Any failure exits with 1, so the
// build never ships hours it could not read.
import fs from "fs/promises";
import path from "path";
import { crmEndpoint, fetchCrmJson, isMainModule } from "./crm.mjs";

export const OPENING_HOURS_PATH = "/api/public/opening-hours";
const OUT_FILE = "./src/auto/openingHours.mjs";

const TIME = /^([01]\d|2[0-3]):[0-5]\d$/;
const DAY = /^\d{4}-\d{2}-\d{2}$/;

const fail = (message) => {
  throw new Error(`opening hours: ${message}`);
};

const isTime = (value) => typeof value === "string" && TIME.test(value);

// The CRM refuses longer exceptions; a guard so a bad feed never walks years of days.
const MAX_EXCEPTION_DAYS = 366;
const DAY_MS = 86_400_000;

// YYYY-MM-DD naming a real calendar day (Date.UTC would roll 2026-02-30 over).
const toUtcDay = (value) => {
  if (typeof value !== "string" || !DAY.test(value)) return null;
  const [year, month, date] = value.split("-").map(Number);
  const ms = Date.UTC(year, month - 1, date);
  return new Date(ms).toISOString().slice(0, 10) === value ? ms : null;
};

// `{closed, opens, closes}`: closed → null times, open → HH:MM with closes > opens.
function hoursOf(entry, where) {
  if (typeof entry?.closed !== "boolean")
    fail(`${where}: \`closed\` is not a boolean`);
  if (entry.closed) return { closed: true, opens: null, closes: null };
  if (!isTime(entry.opens) || !isTime(entry.closes)) {
    fail(`${where}: open hours need HH:MM \`opens\` and \`closes\``);
  }
  if (entry.closes <= entry.opens)
    fail(`${where}: \`closes\` is not after \`opens\``);
  return { closed: false, opens: entry.opens, closes: entry.closes };
}

// Validates the CRM feed `{weekly, exceptions}` (see src/templates/openingHours.mjs)
// and rebuilds it field by field, the week ordered Monday first.
export function toOpeningHours(json) {
  if (!Array.isArray(json?.weekly)) fail("`weekly` is not an array");
  const weekly = json.weekly
    .map((day, i) => {
      if (
        !Number.isInteger(day?.weekday) ||
        day.weekday < 1 ||
        day.weekday > 7
      ) {
        fail(`weekly ${i}: \`weekday\` is not 1..7`);
      }
      return {
        weekday: day.weekday,
        ...hoursOf(day, `weekday ${day.weekday}`),
      };
    })
    .sort((a, b) => a.weekday - b.weekday);
  if (weekly.length !== 7 || weekly.some((d, i) => d.weekday !== i + 1)) {
    fail("`weekly` must hold each weekday 1..7 once");
  }

  if (!Array.isArray(json.exceptions)) fail("`exceptions` is not an array");
  const exceptions = json.exceptions.map((e, i) => {
    const where = `exception ${i}`;
    const from = toUtcDay(e?.from);
    const to = toUtcDay(e?.to);
    if (from === null || to === null) {
      fail(`${where}: \`from\` and \`to\` must be real YYYY-MM-DD days`);
    }
    if (from > to) fail(`${where}: \`from\` is after \`to\``);
    if ((to - from) / DAY_MS + 1 > MAX_EXCEPTION_DAYS) {
      fail(`${where}: longer than ${MAX_EXCEPTION_DAYS} days`);
    }
    if (e.reason !== null && typeof e.reason !== "string") {
      fail(`${where}: \`reason\` is neither a string nor null`);
    }
    return { from: e.from, to: e.to, ...hoursOf(e, where), reason: e.reason };
  });
  return { weekly, exceptions };
}

export function toModule(hours, { source, generatedAt }) {
  return `// generated by npm run fetch-opening-hours from ${source} at ${generatedAt}
export const openingHours = ${JSON.stringify(hours, null, 2)};
`;
}

export async function fetchOpeningHours({
  crmUrl,
  outFile = OUT_FILE,
  ...fetchOptions
} = {}) {
  const url = crmEndpoint(OPENING_HOURS_PATH, crmUrl);
  const hours = toOpeningHours(
    await fetchCrmJson(url, { label: "opening hours", ...fetchOptions }),
  );
  const source = toModule(hours, {
    source: url,
    generatedAt: new Date().toISOString(),
  });
  await fs.mkdir(path.dirname(outFile), { recursive: true });
  await fs.writeFile(outFile, source, "utf8");
  console.log(
    `opening hours: ${hours.exceptions.length} exceptions from ${url} → ${outFile}`,
  );
}

if (isMainModule(import.meta.url)) {
  try {
    await fetchOpeningHours();
  } catch (error) {
    console.error(`fetch-opening-hours failed: ${error.message}`);
    process.exit(1);
  }
}
