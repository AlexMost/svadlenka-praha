// Evaluates the generated module body with an identity `t`, so the test needs
// neither ttag nor a file on disk.
function evaluateModule(source) {
  const body = source
    .replace('import { t } from "ttag";', "")
    .replace("export const getServices = () =>", "return");
  const t = (strings) => strings[0];
  return new Function("t", body)(t);
}

function serve(handler) {
  return new Promise((resolve) => {
    const server = http.createServer(handler);
    server.listen(0, "127.0.0.1", () => {
      const { port } = server.address();
      resolve({
        url: `http://127.0.0.1:${port}`,
        close: () => {
          server.closeAllConnections();
          server.close();
        },
      });
    });
  });
}

const fast = { attempts: 3, delayMs: 1, timeoutMs: 1000 };

test("toServices maps the endpoint to getServices() shape", () => {
  const services = toServices(fixture);
  assert.equal(services.length, 8);
  assert.equal(
    services.reduce((n, s) => n + s.options.length, 0),
    54,
  );
  assert.deepEqual(services[0].title, "Kalhoty a rifli 👖");
  assert.deepEqual(services[0].options[0], ["zkrácení strojem", "300 Kč"]);
  assert.deepEqual(services[0].options[9], ["výměna zipů", "300–500 Kč + zip"]);
});

test("toServices ignores the raw price fields", () => {
  const services = toServices({
    categories: [
      {
        title: "A",
        rows: [
          {
            name: "x",
            price: "od 1\u00a0500 Kč",
            priceKind: "range",
            priceLowCents: 150000,
            priceHighCents: null,
            priceNote: null,
          },
        ],
      },
    ],
  });
  assert.deepEqual(services, [
    { title: "A", options: [["x", "od 1\u00a0500 Kč"]] },
  ]);
});

