test("toModule round-trips every name and price through t``", () => {
  const services = toServices(fixture);
  const source = toModule(services, {
    source: "http://crm",
    generatedAt: "now",
  });
  assert.match(
    source,
    /^\/\/ generated by npm run fetch-services from http:\/\/crm at now\n/,
  );
  assert.match(source, /import \{ t \} from "ttag";/);
  assert.match(source, /title: t`Kalhoty a rifli 👖`/);
  assert.match(source, /\[t`zkrácení strojem`, t`300 Kč`\]/);
  assert.deepEqual(evaluateModule(source), services);
});

test("toModule escapes backticks, ${ and backslashes", () => {
  const services = [
    {
      title: "a `quoted` title",
      options: [["${process.exit(1)}", "C:\\path\\` Kč"]],
    },
  ];
  const source = toModule(services, { source: "x", generatedAt: "y" });
  assert.deepEqual(evaluateModule(source), services);
});

test("fetchPriceList retries until the CRM answers", async () => {
  let calls = 0;
  const crm = await serve((req, res) => {
    calls += 1;
    if (calls < 3) {
      res.statusCode = 502;
      return res.end("Bad Gateway");
    }
    assert.equal(req.url, "/api/public/price-list");
    res.setHeader("content-type", "application/json");
    res.end(JSON.stringify(fixture));
  });
  try {
    const json = await fetchPriceList(`${crm.url}/api/public/price-list`, fast);
    assert.deepEqual(json, fixture);
    assert.equal(calls, 3);
  } finally {
    crm.close();
  }
});

test("fetchPriceList gives up after the last attempt", async () => {
  let calls = 0;
  const crm = await serve((_req, res) => {
    calls += 1;
    res.statusCode = 500;
    res.end("boom");
  });
  try {
    await assert.rejects(
      fetchPriceList(`${crm.url}/api/public/price-list`, fast),
      /500/,
    );
    assert.equal(calls, 3);
  } finally {
    crm.close();
  }
});

for (const [label, handler] of [
  [
    "a 404",
    (res) => {
      res.statusCode = 404;
      res.end("Not Found");
    },
  ],
  ["invalid JSON", (res) => res.end("<html>")],
]) {
  test(`fetchPriceList does not retry ${label}`, async () => {
    let calls = 0;
    const crm = await serve((_req, res) => {
      calls += 1;
      handler(res);
    });
    try {
      await assert.rejects(
        fetchPriceList(`${crm.url}/api/public/price-list`, fast),
      );
      assert.equal(calls, 1);
    } finally {
      crm.close();
    }
  });
}

