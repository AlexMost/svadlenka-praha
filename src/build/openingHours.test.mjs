import { test } from "node:test";
import assert from "node:assert/strict";
import http from "node:http";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";
import {
  toOpeningHours,
  toModule,
  fetchOpeningHours,
} from "./openingHours.mjs";

const fixture = JSON.parse(
  await fs.readFile(
    new URL("./fixtures/opening-hours.json", import.meta.url),
    "utf8",
  ),
);

const clone = () => structuredClone(fixture);

// Evaluates the generated module body, so the test needs no file import.
function evaluateModule(source) {
  const body = source.replace("export const openingHours =", "return");
  return new Function(body)();
}

function serve(handler) {
  return new Promise((resolve) => {
    const server = http.createServer(handler);
    server.listen(0, "127.0.0.1", () => {
      const { port } = server.address();
      resolve({
        url: `http://127.0.0.1:${port}`,
        close: () => {
          server.closeAllConnections();
          server.close();
        },
      });
    });
  });
}

const fast = { attempts: 1, delayMs: 1, timeoutMs: 1000 };

test("toOpeningHours accepts the endpoint response as is", () => {
  assert.deepEqual(toOpeningHours(fixture), fixture);
});

test("toOpeningHours keeps only the known fields and orders the week", () => {
  const json = clone();
  json.weekly.reverse();
  json.weekly[0].id = 7;
  json.exceptions[0].createdAt = "2026-10-01T10:00:00Z";
  json.extra = true;
  assert.deepEqual(toOpeningHours(json), fixture);
});

for (const [label, mutate] of [
  ["no weekly array", (j) => delete j.weekly],
  ["six weekdays", (j) => j.weekly.pop()],
  ["a repeated weekday", (j) => (j.weekly[6].weekday = 1)],
  ["a weekday out of 1..7", (j) => (j.weekly[6].weekday = 8)],
  ["a non-boolean closed", (j) => (j.weekly[0].closed = "no")],
  ["an open day without times", (j) => (j.weekly[0].opens = null)],
  ["a time not HH:MM", (j) => (j.weekly[0].opens = "10.00")],
  ["closes not after opens", (j) => (j.weekly[0].closes = "10:00")],
  ["no exceptions array", (j) => delete j.exceptions],
  ["a date not YYYY-MM-DD", (j) => (j.exceptions[0].from = "28. 10. 2026")],
  ["from after to", (j) => (j.exceptions[1].from = "2027-01-04")],
  ["changed hours without times", (j) => (j.exceptions[0].closes = null)],
  ["a non-string reason", (j) => (j.exceptions[0].reason = 5)],
]) {
  test(`toOpeningHours rejects ${label}`, () => {
    const json = clone();
    mutate(json);
    assert.throws(() => toOpeningHours(json), /^Error: opening hours: /);
  });
}

test("toOpeningHours accepts no exceptions", () => {
  const json = { ...clone(), exceptions: [] };
  assert.deepEqual(toOpeningHours(json).exceptions, []);
});

test("toModule round-trips the data", () => {
  const source = toModule(fixture, {
    source: "https://crm/api/public/opening-hours",
    generatedAt: "2026-10-24T10:00:00.000Z",
  });
  assert.match(source, /^\/\/ generated by npm run fetch-opening-hours/);
  assert.deepEqual(evaluateModule(source), fixture);
});

test("fetchOpeningHours writes the module from crmUrl", async () => {
  let requested;
  const crm = await serve((req, res) => {
    requested = req.url;
    res.end(JSON.stringify(fixture));
  });
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), "opening-hours-"));
  const outFile = path.join(dir, "auto", "openingHours.mjs");
  try {
    await fetchOpeningHours({ crmUrl: `${crm.url}/`, outFile, ...fast });
    assert.equal(requested, "/api/public/opening-hours");
    assert.deepEqual(
      evaluateModule(await fs.readFile(outFile, "utf8")),
      fixture,
    );
  } finally {
    crm.close();
    await fs.rm(dir, { recursive: true, force: true });
  }
});

test("fetchOpeningHours fails on an invalid shape and leaves no module", async () => {
  const crm = await serve((_req, res) =>
    res.end(JSON.stringify({ weekly: [] })),
  );
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), "opening-hours-"));
  const outFile = path.join(dir, "openingHours.mjs");
  try {
    await assert.rejects(
      fetchOpeningHours({ crmUrl: crm.url, outFile, ...fast }),
      /opening hours: /,
    );
    await assert.rejects(fs.access(outFile));
  } finally {
    crm.close();
    await fs.rm(dir, { recursive: true, force: true });
  }
});

test("the script reads CRM_URL, writes the module and exits 1 on a bad feed", async () => {
  const script = fileURLToPath(new URL("./openingHours.mjs", import.meta.url));
  const run = async (body) => {
    const crm = await serve((_req, res) => res.end(body));
    const dir = await fs.mkdtemp(path.join(os.tmpdir(), "opening-hours-"));
    try {
      const { code } = await promisify(execFile)(process.execPath, [script], {
        cwd: dir,
        env: { ...process.env, CRM_URL: crm.url },
      }).then(
        () => ({ code: 0 }),
        (error) => ({ code: error.code }),
      );
      const outFile = path.join(dir, "src", "auto", "openingHours.mjs");
      const source = await fs.readFile(outFile, "utf8").catch(() => null);
      return { code, source };
    } finally {
      crm.close();
      await fs.rm(dir, { recursive: true, force: true });
    }
  };

  const good = await run(JSON.stringify(fixture));
  assert.equal(good.code, 0);
  assert.deepEqual(evaluateModule(good.source), fixture);

  const bad = await run(JSON.stringify({ exceptions: [] }));
  assert.equal(bad.code, 1);
  assert.equal(bad.source, null);
});
